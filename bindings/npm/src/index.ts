/**
 * State-preserving deterministic procedural audio generator.
 *
 * @public
 * @example
 * ```typescript
 * import { SomniaEngine, ScaleType } from "@sxnnyside/somnia";
 *
 * const engine = new SomniaEngine(424242);
 * const note = engine.nextEvent(ScaleType.Dorian, 0, 120);
 * console.log(`Frequency: ${note.frequency} Hz, Duration: ${note.durationMs} ms`);
 * ```
 */
export class SomniaEngine {
  /**
   * Internal stream state.
   * @internal
   */
  private state: StreamStateQ8 = {
    phaseQ8: 0,
    stepIndex: 0,
  };

  /**
   * Creates a new instance of the Somnia generator engine.
   *
   * @param seed - Initial PRNG integer seed.
   */
  constructor(public seed: number = 424242) {}

  /**
   * Evaluates and yields the next procedural note event.
   *
   * @param scale - Musical mode to quantize pitches into. Defaults to Dorian.
   * @param rootNote - Chromatic transposition in semitones (0 = C). Defaults to 0.
   * @param bpm - Playback tempo in Beats Per Minute (must be > 0). Defaults to 120.
   * @param hasRests - Whether to probabilistically insert musical pauses. Defaults to true.
   * @returns Generated note event structure.
   * @throws RangeError - If bpm is less than or equal to 0.
   */
  public nextEvent(
    scale: ScaleType = ScaleType.Dorian,
    rootNote: number = 0,
    bpm: number = 120,
    hasRests: boolean = true
  ): NoteEvent {
    if (bpm <= 0) {
      throw new RangeError("BPM must be greater than 0");
    }
    // 0.25 timeStep in Q8 fixed-point arithmetic (256 * 0.25 = 64)
    const timeStepQ8 = 64;
    this.state.phaseQ8 = (this.state.phaseQ8 + timeStepQ8) & 0x7fffffff;
    this.state.stepIndex++;

    // Deterministic pseudo-random integer hash
    let h = (this.seed ^ (this.state.stepIndex * 1664525 + 1013904223)) >>> 0;
    h = ((h ^ (h >>> 16)) * 0x45d9f3b) >>> 0;
    h = ((h ^ (h >>> 16)) * 0x45d9f3b) >>> 0;
    h = (h ^ (h >>> 16)) >>> 0;

    // Rest evaluation (15% probability if rests enabled)
    if (hasRests && (h % 100) < 15) {
      const stepDurationMs = Math.round(60000 / bpm);
      return {
        frequency: 0,
        durationMs: stepDurationMs,
        label: "REST",
        midiNote: 0,
        velocity: 0,
        isRest: true,
      };
    }

    const intervals = SCALE_INTERVALS[scale];
    const degree = h % intervals.length;
    const octaveOffset = (Math.floor(h / 7) % 3) - 1; // -1, 0, +1 octave
    const baseOctave = 4 + octaveOffset;

    const midiNote = Math.min(127, Math.max(0, 12 * baseOctave + rootNote + intervals[degree]));
    const frequency = MIDI_FREQUENCIES[midiNote] || 440;
    const noteName = `${NOTE_NAMES[midiNote % 12]}${Math.floor(midiNote / 12) - 1}`;

    const durationRatio = [0.25, 0.5, 0.75, 1.0][(h >>> 8) % 4];
    const durationMs = Math.round((60000 / bpm) * durationRatio);
    const velocity = 70 + ((h >>> 12) % 45); // 70..115

    return {
      frequency,
      durationMs,
      label: noteName,
      midiNote,
      velocity,
      isRest: false,
    };
  }

  /**
   * Resets the internal generator state, optionally applying a new seed.
   *
   * @param newSeed - Optional new integer seed value.
   */
  public reset(newSeed?: number): void {
    if (newSeed !== undefined) {
      this.seed = newSeed;
    }
    this.state = {
      phaseQ8: 0,
      stepIndex: 0,
    };
  }

  /**
   * Returns a snapshot copy of the current generator stream state.
   *
   * @returns Current fixed-point stream state.
   */
  public getState(): Readonly<StreamStateQ8> {
    return { ...this.state };
  }
}

/**
 * Controller handle returned by playNote for runtime cancellation.
 *
 * @public
 */
export interface NotePlaybackHandle {
  /** Immediately silences and stops the oscillator voice. */
  stop: () => void;
}

/**
 * Synthesizes and plays a procedural note event using the browser Web Audio API.
 *
 * @param ctx - Active AudioContext instance.
 * @param event - Procedural NoteEvent yielded by SomniaEngine.
 * @param destination - Optional audio node destination. Defaults to ctx.destination.
 * @returns Playback handle with a stop() method, or null if the event is a rest.
 *
 * @public
 * @example
 * ```typescript
 * import { SomniaEngine, playNote } from "@sxnnyside/somnia";
 *
 * const ctx = new AudioContext();
 * const engine = new SomniaEngine();
 * const note = engine.nextEvent();
 * const handle = playNote(ctx, note);
 * // Later: handle?.stop();
 * ```
 */
export function playNote(
  ctx: AudioContext,
  event: NoteEvent,
  destination?: AudioNode
): NotePlaybackHandle | null {
  if (event.isRest || event.frequency <= 0) {
    return null;
  }

  const dest = destination || ctx.destination;
  const now = ctx.currentTime;
  const durationSec = event.durationMs / 1000;

  const osc = ctx.createOscillator();
  const gain = ctx.createGain();

  osc.type = "sine";
  osc.frequency.setValueAtTime(event.frequency, now);

  const peakGain = (event.velocity / 127) * 0.25;
  gain.gain.setValueAtTime(0.001, now);
  gain.gain.exponentialRampToValueAtTime(peakGain, now + 0.02);
  gain.gain.exponentialRampToValueAtTime(0.001, now + durationSec);

  osc.connect(gain);
  gain.connect(dest);

  osc.start(now);
  osc.stop(now + durationSec + 0.05);

  return {
    stop: () => {
      gain.gain.cancelScheduledValues(ctx.currentTime);
      gain.gain.setValueAtTime(0.001, ctx.currentTime);
      osc.stop(ctx.currentTime + 0.02);
    },
  };
}
