/**
 * @packageDocumentation
 * Somnia TypeScript / Web Audio API procedural generative sound engine.
 *
 * Provides deterministic, zero-allocation procedural melody generation,
 * 12-TET tuning lookup tables, and real-time Web Audio API playback helpers.
 */

/**
 * Supported musical modes and scale quantizations.
 *
 * @public
 */
export enum ScaleType {
  /** Lydian mode (Major with augmented 4th: 1, 2, 3, #4, 5, 6, 7). */
  Lydian = 0,
  /** Minor Pentatonic scale (1, b3, 4, 5, b7). */
  MinorPentatonic = 1,
  /** Major Pentatonic scale (1, 2, 3, 5, 6). */
  MajorPentatonic = 2,
  /** Dorian mode (Minor with major 6th: 1, 2, b3, 4, 5, 6, b7). */
  Dorian = 3,
  /** Natural Minor / Aeolian mode (1, 2, b3, 4, 5, b6, b7). */
  Minor = 4,
  /** Major / Ionian mode (1, 2, 3, 4, 5, 6, 7). */
  Major = 5,
  /** Mixolydian mode (Major with flat 7th: 1, 2, 3, 4, 5, 6, b7). */
  Mixolydian = 6,
  /** Phrygian mode (Minor with flat 2nd: 1, b2, b3, 4, 5, b6, b7). */
  Phrygian = 7,
  /** Hexatonic Blues scale (1, b3, 4, b5, 5, b7). */
  Blues = 8,
  /** Traditional Japanese Hirajoshi pentatonic scale (1, 2, b3, 5, b6). */
  Hirajoshi = 9,
}

/**
 * Melodic movement and voice leading modes.
 *
 * @public
 */
export enum PlayMode {
  /** Stepwise continuous melodic traversal. */
  Melody = 0,
  /** Broken chord arpeggiation across octaves. */
  Arpeggio = 1,
  /** Harmonic cluster chords and dyads. */
  Chords = 2,
}

/**
 * Rhythmic metric time signatures.
 *
 * @public
 */
export enum TimeSignature {
  /** Common time (4 beats per measure). */
  FourFour = 0,
  /** Triple meter (3 beats per measure). */
  ThreeFour = 1,
  /** Complex additive meter (7 eighth-notes per measure). */
  SevenEight = 2,
}

/**
 * Discrete musical event generated by the procedural engine.
 *
 * @public
 */
export interface NoteEvent {
  /** Fundamental frequency in Hertz (Hz). */
  frequency: number;
  /** Duration of the note in milliseconds. */
  durationMs: number;
  /** Scientific pitch label (e.g. "C4", "A#5", "REST"). */
  label: string;
  /** MIDI note number (0..127). */
  midiNote: number;
  /** MIDI velocity dynamic level (0..127). */
  velocity: number;
  /** Whether this event represents a musical rest (silence). */
  isRest: boolean;
}

/**
 * Internal stream state representation for continuous procedural generation.
 *
 * @public
 */
export interface StreamState {
  /** Integer coordinate cell index. */
  cell: number;
  /** Normalized sub-cell phase fraction [0.0, 1.0). */
  frac: number;
  /** Monotonic step counter. */
  step: number;
}

/**
 * Backward compatibility alias for StreamState.
 *
 * @deprecated Use StreamState instead.
 */
export type StreamStateQ8 = StreamState;

